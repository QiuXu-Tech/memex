/**
 * Export this repository's nine source packages in DSH-upstream shape.
 *
 * The public DSH runtime does not (yet) publish a plugin monorepo to send a PR
 * to; this script prepares the tree so the packages can be contributed once an
 * upstream location exists. It rewrites the workspace scope `@qiuxu/*` to
 * `@deepseek-ai/*`, drops the local-only bundle, resets package metadata for
 * publishing, and writes a manifest + README for upstream reviewers.
 *
 * Output (git-ignored):
 *   dist/upstream/packages/memex-seam
 *   dist/upstream/packages/memex-local
 *   dist/upstream/packages/memex-checkpoint
 *   dist/upstream/packages/memex-tool
 *   dist/upstream/packages/memex-command
 *   dist/upstream/packages/memex-api
 *   dist/upstream/packages/memex-ui
 *   dist/upstream/packages/memex-evict
 *   dist/upstream/packages/memex-compress
 *   dist/upstream/manifest.json
 *   dist/upstream/README.md
 *
 * Usage: node scripts/export-upstream.mjs [--out dist/upstream]
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, statSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = resolve(fileURLToPath(new URL('..', import.meta.url)))
const arg = (name, fallback) => {
  const index = process.argv.indexOf(`--${name}`)
  return index >= 0 ? process.argv[index + 1] : fallback
}
const out = resolve(here, arg('out', 'dist/upstream'))
const packages = [
  'memex-core',
  'memex-seam',
  'memex-local',
  'memex-checkpoint',
  'memex-tool',
  'memex-command',
  'memex-api',
  'memex-ui',
  'memex-evict',
  'memex-compress',
]

rmSync(out, { recursive: true, force: true })
mkdirSync(join(out, 'packages'), { recursive: true })

const rewrite = (text) => text
  .replaceAll('@qiuxu/memex', '@deepseek-ai/memex')
  .replaceAll('@qiuxu/', '@deepseek-ai/')

const manifest = { format: 1, exportedAt: new Date().toISOString(), source: 'QiuXu-Tech/memex', packages: [] }

for (const name of packages) {
  const source = join(here, 'packages', name)
  if (!existsSync(join(source, 'package.json'))) throw new Error(`missing package: ${source}`)
  const target = join(out, 'packages', name)
  mkdirSync(target, { recursive: true })
  for (const entry of ['index.js', 'lib', 'client.js', 'package.json']) {
    const from = join(source, entry)
    if (!existsSync(from)) continue
    const to = join(target, entry)
    if (statSync(from).isDirectory()) cpSync(from, to, { recursive: true })
    else cpSync(from, to)
  }
  // Rewrite imports and package names.
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name)
      if (entry.isDirectory()) walk(path)
      else if (/\.(js|mjs|json)$/.test(entry.name)) writeFileSync(path, rewrite(readFileSync(path, 'utf8')))
    }
  }
  walk(target)
  const manifestPath = join(target, 'package.json')
  const pkg = JSON.parse(readFileSync(manifestPath, 'utf8'))
  pkg.name = `@deepseek-ai/${name}`
  pkg.version = pkg.version ?? '0.1.0'
  pkg.private = false
  pkg.license = 'MIT'
  pkg.author = 'QiuXu-Tech'
  pkg.repository = { type: 'git', url: 'git+https://github.com/QiuXu-Tech/memex.git' }
  pkg.homepage = 'https://qiuxu-tech.github.io/memex/'
  writeFileSync(manifestPath, `${JSON.stringify(pkg, null, 2)}\n`)
  manifest.packages.push({ name: pkg.name, dir: `packages/${name}`, description: pkg.description ?? '' })
}

writeFileSync(join(out, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
writeFileSync(join(out, 'README.md'), `# memex — upstream export

Generated by \`node scripts/export-upstream.mjs\` from QiuXu-Tech/memex.

The public DSH runtime does not currently publish a plugin package repository; this tree is the proposal for an upstream contribution:

| Package | Role |
|---|---|
| \`@deepseek-ai/memex-seam\` | Cordis-free service contract, record vocabulary, shared query-term extractor |
| \`@deepseek-ai/memex-local\` | SQLite + markdown backend (hot/cold, FTS, compression history) |
| \`@deepseek-ai/memex-checkpoint\` | Checkpoint policy (archive/receipt/catalog/recall/notice) |
| \`@deepseek-ai/memex-tool\` | Seven model tools + stable prompt section |
| \`@deepseek-ai/memex-command\` | \`/memory\` command set |
| \`@deepseek-ai/memex-api\` | Nine \`/api/memory.*\` routes |
| \`@deepseek-ai/memex-ui\` | Web client half (panel + context-ring bridge) |
| \`@deepseek-ai/memex-evict\` | L1 eviction policy |
| \`@deepseek-ai/memex-compress\` | Capacity compression (cold/digest) |

Before sending an upstream PR:

1. Move the offline harness into the upstream test layout (per-package tests + integration smoke) and run it against the real host.
2. Confirm license headers, \`files\`/exports, and peer-dependency versions against the DSH release being targeted.
3. Decide whether the bundle/patch stays in this repo (local install) or becomes an upstream recipe; the bundle is intentionally not part of this export.
4. Add a user-facing config page and changelog entry upstream.
`)
console.log(`upstream export: ${out}`)
console.log(`packages: ${manifest.packages.length}`)
