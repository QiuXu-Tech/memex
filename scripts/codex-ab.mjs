#!/usr/bin/env node
// Codex CLI → Memex live A/B bridge.
//
// Generates the synthetic long-horizon fixture with live-ab.mjs --emit-prompts,
// asks the local `codex exec` (non-interactive) model to answer the control and
// treatment prompts, grades the replies against the fixture's expected FACT ids,
// and writes a shareable JSON report. No API key is read or stored.
//
// Usage:
//   node scripts/codex-ab.mjs --model gpt-6.1-sol
//   node scripts/codex-ab.mjs --model gpt-6.1-terra --seeds 3 --probes 20
//   node scripts/codex-ab.mjs --codex-bin /path/to/codex --out /tmp/codex-ab.json

import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '..')
const NODE = process.execPath
const arg = (name, fallback) => {
  const index = process.argv.indexOf(`--${name}`)
  return index >= 0 ? process.argv[index + 1] : fallback
}
const MODEL = arg('model', 'gpt-6.1-sol')
const SEEDS = Number(arg('seeds', 3))
const PROBES = Number(arg('probes', 20))
const TURNS = Number(arg('turns', 300))
const CODEX = arg('codex-bin', 'codex')
const OUT = resolve(arg('out', join(tmpdir(), 'memex-codex-live-ab.json')))
const KEEP = process.argv.includes('--keep')

const run = (bin, args, options = {}) => spawnSync(bin, args, { encoding: 'utf8', ...options })
const version = run(CODEX, ['--version'])
if (version.error !== undefined || version.status !== 0) {
  console.error(`Codex CLI not runnable (${CODEX}). Install it first: https://github.com/openai/codex`)
  console.error(version.error?.message ?? version.stderr?.trim() ?? '')
  process.exit(1)
}
const nodeVersion = Number(process.versions.node.split('.')[0])
if (nodeVersion < 22) {
  console.error(`Node ${process.versions.node} found; Memex requires Node >= 22 (node:sqlite).`)
  process.exit(1)
}

const parseAnswers = (text) => {
  const answers = {}
  for (const line of String(text ?? '').split('\n')) {
    const match = line.match(/^\s*Q(\d+)\s*:\s*(.+?)\s*$/)
    if (match !== null) answers[Number(match[1])] = match[2].replace(/^`|`$/g, '')
  }
  return answers
}
const grade = (answers, expected) => {
  const rows = expected.map((probe) => ({ ...probe, answer: answers[probe.index] ?? '', correct: answers[probe.index] === probe.expected }))
  return { rows, correct: rows.filter((row) => row.correct).length, total: rows.length }
}

const report = {
  format: 1,
  kind: 'live-ab-codex-result',
  generatedAt: new Date().toISOString(),
  provider: 'codex-cli',
  model: MODEL,
  method: 'codex exec --skip-git-repo-check --sandbox read-only --output-last-message; control/treatment generated by scripts/live-ab.mjs --emit-prompts',
  seeds: [],
  aggregate: {},
  raw: [],
  caveats: [
    'Control/treatment prompts are synthetic fixtures; do not include private data.',
    'The Codex agent has its own tools; the prompt asks it not to use them. Review the raw replies before publishing.',
    'Usage/token counts are not captured by this bridge.',
  ],
}
let allControl = []
let allTreatment = []
let allEvictedControl = []
let allEvictedTreatment = []
const tempRoot = mkdtempSync(join(tmpdir(), 'memex-codex-ab-'))
try {
  for (let seed = 1; seed <= SEEDS; seed += 1) {
    const promptsDir = join(tempRoot, `seed-${seed}`)
    const emit = run(NODE, ['--import', join(REPO, 'test/register.mjs'), join(REPO, 'scripts/live-ab.mjs'), '--emit-prompts', promptsDir, '--probes', String(PROBES), '--turns', String(TURNS), '--seed', String(seed), '--model', MODEL])
    if (emit.status !== 0) throw new Error(`fixture generation failed (seed ${seed}): ${emit.stderr.slice(-500)}`)
    const plan = JSON.parse(readFileSync(join(promptsDir, 'plan.json'), 'utf8'))
    const controlPrompt = readFileSync(join(promptsDir, 'control.txt'), 'utf8')
    const treatmentPrompt = readFileSync(join(promptsDir, 'treatment.txt'), 'utf8')
    const runCodex = (label, prompt) => {
      const workDir = join(promptsDir, label)
      const outFile = join(promptsDir, `${label}.out`)
      const args = ['exec', '--skip-git-repo-check', '--sandbox', 'read-only', '--model', MODEL, '--cd', workDir, '--output-last-message', outFile, prompt]
      const result = run(CODEX, args, { cwd: workDir, maxBuffer: 16 * 1024 * 1024 })
      const text = existsSync(outFile) ? readFileSync(outFile, 'utf8') : result.stdout ?? ''
      report.raw.push({ seed, label, status: result.status, stderrTail: (result.stderr ?? '').slice(-1200), textTail: String(text).slice(-4000) })
      return text
    }
    // Keep the two work dirs separate so a run cannot see the other condition's files.
    for (const label of ['control', 'treatment']) mkdirSync(join(promptsDir, label), { recursive: true })
    const controlAnswers = parseAnswers(runCodex('control', controlPrompt))
    const treatmentAnswers = parseAnswers(runCodex('treatment', treatmentPrompt))
    const control = grade(controlAnswers, plan.probes)
    const treatment = grade(treatmentAnswers, plan.probes)
    // The fixed harness records inTail/evicted for every probe in plan.json.
    // Fall back to turn-based classification only for old plans.
    const evictedSet = new Set(plan.probes.filter((probe) => probe.evicted === true || probe.inTail === false).map((probe) => probe.index))
    allControl.push(...control.rows.map((row) => row.correct))
    allTreatment.push(...treatment.rows.map((row) => row.correct))
    allEvictedControl.push(...control.rows.filter((row) => evictedSet.has(row.index)).map((row) => row.correct))
    allEvictedTreatment.push(...treatment.rows.filter((row) => evictedSet.has(row.index)).map((row) => row.correct))
    report.seeds.push({ seed, turns: plan.turns, tailCount: plan.tailCount, tailIds: plan.tailIds, probes: plan.probes.length, evictedProbes: evictedSet.size, control, treatment })
  }
} catch (error) {
  console.error(`codex-ab failed: ${error.message}`)
  process.exit(1)
} finally {
  if (!KEEP) rmSync(tempRoot, { recursive: true, force: true })
}

const summary = (values) => ({ correct: values.filter(Boolean).length, n: values.length, accuracy: values.length === 0 ? 0 : Math.round((values.filter(Boolean).length / values.length) * 10000) / 10000 })
report.aggregate = {
  control: summary(allControl),
  treatment: summary(allTreatment),
  evictedControl: summary(allEvictedControl),
  evictedTreatment: summary(allEvictedTreatment),
}
writeFileSync(OUT, JSON.stringify(report, null, 2) + '\n')
console.log(`\nCodex (${MODEL}) live A/B`)
console.log(`control:   ${report.aggregate.control.correct}/${report.aggregate.control.n} (${(report.aggregate.control.accuracy * 100).toFixed(1)}%)`)
console.log(`treatment: ${report.aggregate.treatment.correct}/${report.aggregate.treatment.n} (${(report.aggregate.treatment.accuracy * 100).toFixed(1)}%)`)
console.log(`evicted:   ${report.aggregate.evictedControl.correct}/${report.aggregate.evictedControl.n} → ${report.aggregate.evictedTreatment.correct}/${report.aggregate.evictedTreatment.n}`)
console.log(`\nReport: ${OUT}`)
console.log('Share it on issue #1 (https://github.com/QiuXu-Tech/memex/issues/1) or open a PR adding it under docs/assets/benchmarks/.')
